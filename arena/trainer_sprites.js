    const SOURCE_PRIORITY = Object.freeze(['B2W2', 'BW', 'E', 'FRLG', 'RS', 'JP', 'OTHER']);
    const SPRITE_BASE_PATH = 'assets/sprites/';

    const spritesByName = SPRITES.reduce((index, sprite) => {
        const key = normalizeTrainerName(sprite.name);

        if (!index.has(key)) index.set(key, []);
        index.get(key).push(sprite);

        return index;
    }, new Map());

    spritesByName.forEach(sprites => {
        sprites.sort((left, right) => getSourceRank(left.source) - getSourceRank(right.source));
    });

    function resolveSprite(name, explicitSprite = null) {
        const candidateNames = getCandidateNames(name, explicitSprite);

        for (const candidateName of candidateNames) {
            const sprite = findBestSprite(candidateName);

            if (sprite) {
                return {
                    file: sprite.file,
                    name: sprite.name,
                    path: getSpritePath(sprite.file),
                    source: sprite.source
                };
            }
        }

        const fallbackName = normalizeTrainerName(explicitSprite || name || 'Gamer');
        const fallbackFile = fallbackName + '.png';

        return {
            file: fallbackFile,
            name: fallbackName,
            path: getSpritePath(fallbackFile),
            source: 'OTHER'
        };
    }

    function getDisplayName(name) {
        return stripTerminalGender(normalizeTrainerName(name));
    }

    function getCandidateNames(name, explicitSprite) {
        const candidates = [];

        addCandidate(candidates, explicitSprite);
        addCandidate(candidates, name);
        addCandidate(candidates, stripTerminalGender(name));
        addCandidate(candidates, stripTerminalGender(explicitSprite));

        return candidates;
    }

    function addCandidate(candidates, name) {
        const normalizedName = normalizeTrainerName(name);

        if (!normalizedName || candidates.includes(normalizedName)) return;

        candidates.push(normalizedName);
    }

    function findBestSprite(name) {
        const sprites = spritesByName.get(normalizeTrainerName(name));

        return sprites && sprites.length > 0 ? sprites[0] : null;
    }

    function normalizeTrainerName(name) {
        return String(name || '').trim().replace(/\s+/g, ' ');
    }

    function stripTerminalGender(name) {
        return normalizeTrainerName(name).replace(/\s+[MF]$/u, '');
    }

    function getSourceRank(source) {
        const rank = SOURCE_PRIORITY.indexOf(source);

        return rank === -1 ? SOURCE_PRIORITY.length : rank;
    }

    function getSpritePath(file) {
        return SPRITE_BASE_PATH + encodeURIComponent(file);
    }

    global.TrainerSprites = Object.freeze({
        getDisplayName,
        resolveSprite,
        sprites: SPRITES
    });
